// Builds the Relstrat MCP worker into mcp/dist by concatenating the dashboard's
// data constants (sliced straight out of site/App.jsx so the two never drift)
// with the JSON-RPC server in src/server.js. No bundler is needed: the output is
// one dependency-free ES module plus wrangler.toml, which `gizmos push --mcp`
// uploads as-is.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = readFileSync(join(here, "..", "site", "App.jsx"), "utf8");

function slice(startMarker, endMarker) {
  const a = app.indexOf(startMarker);
  const b = app.indexOf(endMarker, a);
  if (a < 0 || b < 0) throw new Error(`Marker not found: ${startMarker} .. ${endMarker}`);
  return app.slice(a, b);
}

// Pure data: MONTHS through the notes-analysis blocks, stopping at the theme colours.
const data = slice("const MONTHS = [", "const LIGHT_COLOR = ");
const products = slice('const PRODUCTS = ["HSIA"', "\n") + "\n" + slice('const SCOPES = ["All"', "\n") + "\n";
const deriveAll = slice("(function deriveAll() {", "})();") + "})();\n";
for (const chunk of [data, products, deriveAll]) {
  if (/\bReact\b|useState|useEffect|<[A-Za-z]/.test(chunk)) throw new Error("Data slice contains UI code; check the markers in build.mjs");
}

// Pure helpers the page model reuses verbatim: scorecard indicators, the HSIA pain-point
// grouping, issue → theme mapping and the sub-page registry.
const helpers = slice("const INDICATORS = [", "\n// ---------------------------------------------------------------------------\n// Executive summary deck export");
if (/\bReact\b|useState|useEffect|<[A-Za-z]/.test(helpers)) throw new Error("Helper slice contains UI code; check the markers in build.mjs");

// Hand-written analysis content that lives inside the dashboard component (recommendations
// and the cross-analysis matrices). Each is lifted into a module-level constant so the page
// model serves exactly what the page shows.
function sliceFrom(anchor, startMarker, endMarker, rename) {
  const at = app.indexOf(anchor);
  if (at < 0) throw new Error(`Anchor not found: ${anchor}`);
  const a = app.indexOf(startMarker, at);
  const b = app.indexOf(endMarker, a);
  if (a < 0 || b < 0) throw new Error(`Marker not found after ${anchor}: ${startMarker} .. ${endMarker}`);
  return `const ${rename} = ${app.slice(a + startMarker.length, b + endMarker.length).trim()}\n`;
}
const lifted = [
  sliceFrom("  const TV_RECS = [", "const TV_RECS = ", "\n  ];", "TV_RECS"),
  sliceFrom("  const HSIA_SENTIMENT_RECS = [", "const HSIA_SENTIMENT_RECS = ", "\n  ];", "HSIA_SENTIMENT_RECS"),
  sliceFrom("  const HSIA_RECS = [", "const HSIA_RECS = ", "\n  ];", "HSIA_RECS"),
  sliceFrom("function TvCrossPage() {", "const MATRIX = ", "\n    ];", "TV_CROSS_MATRIX"),
  sliceFrom("function TvCrossPage() {", "const rising = ", "\n    ];", "TV_CROSS_RISING"),
  sliceFrom("function TvCrossPage() {", "const falling = ", "\n    ];", "TV_CROSS_FALLING"),
  sliceFrom("function HsiaCrossPage() {", "const MATRIX = ", "\n    ];", "HSIA_CROSS_MATRIX"),
  sliceFrom("function HsiaCrossPage() {", "const rising = ", "\n    ];", "HSIA_CROSS_RISING"),
  sliceFrom("function HsiaCrossPage() {", "const falling = ", "\n    ];", "HSIA_CROSS_FALLING"),
  sliceFrom("function TvSentimentPage() {", "<Recs items={", "\n          ]}", "TV_SENTIMENT_RECS").replace(/\]\}\s*$/, "];")
].join("\n");
if (/useState|useEffect|<[A-Z][a-z]+ /.test(lifted)) throw new Error("Lifted constants contain UI code; check the markers in build.mjs");

const server = readFileSync(join(here, "src", "server.js"), "utf8");
const pages = readFileSync(join(here, "src", "pages.js"), "utf8") + "\n" + readFileSync(join(here, "src", "display.js"), "utf8");
const banner = `// Generated by mcp/build.mjs from site/App.jsx — do not edit by hand.\n// Dashboard data block begins here.\n`;
const out = banner + data + products + deriveAll + "\n// ---- dashboard helpers ----\n" + helpers + "\n// ---- dashboard page content lifted from the component ----\n" + lifted + "\n// ---- MCP server ----\n" + server + "\n// ---- page model ----\n" + pages;

mkdirSync(join(here, "dist", "src"), { recursive: true });
writeFileSync(join(here, "dist", "src", "index.js"), out);
copyFileSync(join(here, "wrangler.toml"), join(here, "dist", "wrangler.toml"));
copyFileSync(join(here, "BINDING.md"), join(here, "dist", "BINDING.md")); // the [[gizmos_binding]] doc must ship at the bundle root
console.log(`mcp/dist/src/index.js written (${(out.length / 1024).toFixed(0)} KB)`);
