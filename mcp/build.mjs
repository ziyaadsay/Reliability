// Builds the Relstrat MCP worker into mcp/dist by concatenating the dashboard's
// data constants (sliced straight out of site/App.jsx so the two never drift)
// with the JSON-RPC server in src/server.js. No bundler is needed: the output is
// one dependency-free ES module plus wrangler.toml, which `gizmos push --mcp`
// uploads as-is.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = readFileSync(join(here, "..", "site", "App.jsx"), "utf8");

function slice(startMarker, endMarker) {
  const a = app.indexOf(startMarker);
  const b = app.indexOf(endMarker, a);
  if (a < 0 || b < 0) throw new Error(`Marker not found: ${startMarker} .. ${endMarker}`);
  return app.slice(a, b);
}

// Pure data: MONTHS through the notes-analysis blocks, stopping at the theme colours.
const data = slice("const MONTHS = [", "const LIGHT_COLOR = ");
const products = slice('const PRODUCTS = ["HSIA"', "\n") + "\n";
const deriveAll = slice("(function deriveAll() {", "})();") + "})();\n";
for (const chunk of [data, products, deriveAll]) {
  if (/\bReact\b|useState|useEffect|<[A-Za-z]/.test(chunk)) throw new Error("Data slice contains UI code; check the markers in build.mjs");
}

const server = readFileSync(join(here, "src", "server.js"), "utf8");
const banner = `// Generated by mcp/build.mjs from site/App.jsx — do not edit by hand.\n// Dashboard data block begins here.\n`;
const out = banner + data + products + deriveAll + "\n// ---- MCP server ----\n" + server;

mkdirSync(join(here, "dist", "src"), { recursive: true });
writeFileSync(join(here, "dist", "src", "index.js"), out);
copyFileSync(join(here, "wrangler.toml"), join(here, "dist", "wrangler.toml"));
copyFileSync(join(here, "BINDING.md"), join(here, "dist", "BINDING.md")); // the [[gizmos_binding]] doc must ship at the bundle root
console.log(`mcp/dist/src/index.js written (${(out.length / 1024).toFixed(0)} KB)`);
